#!/usr/bin/env python3
"""Derive tokens/llm/token-catalog.json from the real token files (R10).

Every leaf token ({"$value": ...}) in tokens/00-foundation, 10-semantic,
20-component and 30-layout is listed by id, grouped by its real top-level key;
the two themes are copied as resolve maps; supported fonts and the spacing scale
are read from the foundation values. Nothing is hand-typed.

    python3 extraction/build_token_catalog.py          # rewrite the catalog
    python3 extraction/build_token_catalog.py --check  # exit 1 if the file on disk differs

verify_all.py (check token-catalog) calls build() and compares, so the catalog
cannot drift from the token files.
"""
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAYERS = [("foundation", "00-foundation"), ("semantic", "10-semantic"), ("component", "20-component"), ("layout", "30-layout")]
OUT = "tokens/llm/token-catalog.json"


def _load(rel):
    with open(os.path.join(REPO, rel), encoding="utf-8") as f:
        return json.load(f)


def _leaves(o, path, out):
    if isinstance(o, dict):
        if "$value" in o:
            out[path] = o
            return
        for k, v in o.items():
            if not k.startswith("$"):
                _leaves(v, (path + "." + k) if path else k, out)


def build():
    layers, all_leaves = {}, {}
    for name, d in LAYERS:
        cats = {}
        for f in sorted(os.listdir(os.path.join(REPO, "tokens", d))):
            if not f.endswith(".json"):
                continue
            leaves = {}
            _leaves(_load("tokens/%s/%s" % (d, f)), "", leaves)
            for tid, leaf in leaves.items():
                # semantic tone roles are referenced as tone.<role> (themes resolve them)
                cats.setdefault(tid.split(".")[0], []).append(tid)
                all_leaves[tid] = (name, f, leaf)
        layers[name] = {k: v for k, v in sorted(cats.items())}
    themes = {}
    for f in sorted(os.listdir(os.path.join(REPO, "tokens/themes"))):
        t = _load("tokens/themes/" + f)
        themes[t["theme"]] = {"tone." + k: v.strip("{}") for k, v in sorted(t["resolve"].items())}
    fam = {tid: leaf["$value"] for tid, (layer, _f, leaf) in all_leaves.items() if layer == "foundation" and tid.startswith("fontFamily.")}
    spacing = {tid: leaf["$value"] for tid, (layer, _f, leaf) in all_leaves.items() if layer == "foundation" and tid.startswith("spacing.scale.")}
    return {
        "version": "2.0.0",
        "$description": "GENERATED by extraction/build_token_catalog.py from tokens/00-foundation, 10-semantic, 20-component, 30-layout and tokens/themes. Do not edit by hand: verify_all (token-catalog) rebuilds and compares.",
        "tokenCount": len(all_leaves),
        "layers": layers,
        "categories": layers["foundation"],
        "semanticRoles": sorted(layers["semantic"].get("tone", [])) + sorted(layers["semantic"].get("status", [])),
        "themes": themes,
        "supportedFonts": {k: v for k, v in sorted(fam.items())},
        "spacingScalePx": {k: v for k, v in sorted(spacing.items(), key=lambda kv: kv[1])},
    }


def main(argv):
    want = build()
    p = os.path.join(REPO, OUT)
    if "--check" in argv:
        have = json.load(open(p, encoding="utf-8")) if os.path.isfile(p) else None
        if have != want:
            print("token-catalog.json differs from the token files; run build_token_catalog.py")
            return 1
        print("token-catalog.json matches the token files (%d tokens)" % want["tokenCount"])
        return 0
    with open(p, "w", encoding="utf-8") as f:
        json.dump(want, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print("wrote %s (%d tokens)" % (OUT, want["tokenCount"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
